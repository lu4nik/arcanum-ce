#!/usr/bin/env python3
"""Regenerate src/lit25d_shaders.h from the Vulkan GLSL sources here.

Each shader is compiled with glslang to SPIR-V and cross-compiled with
spirv-cross to MSL 2.1 (Metal) and HLSL SM 5.1 (Direct3D 12, compiled to DXBC
at run time). The results are embedded as C strings, so nothing has to be
shipped next to the game. Run this after editing a shader; needs `glslang`
and `spirv-cross` (brew install glslang spirv-cross).
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "lit25d_shaders.h")

SHADERS = [
    ("lit25d_vert", "lit25d.vert", "vert"),
    ("lit25d_geo", "lit25d-geo.frag", "frag"),
    ("lit25d_light", "lit25d-light.frag", "frag"),
]


def run(*cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("%s\n%s%s" % (" ".join(cmd), r.stdout, r.stderr))
    return r.stdout


def c_string(text):
    lines = []
    for line in text.split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        lines.append('    "%s\\n"' % esc)
    return "\n".join(lines)


def main():
    parts = ["// Generated by shaders/lit25d/gen.py; do not edit.\n"]
    with tempfile.TemporaryDirectory() as tmp:
        for name, src, stage in SHADERS:
            spv = os.path.join(tmp, name + ".spv")
            run("glslang", "-V", "--quiet", "-S", stage, "-o", spv, os.path.join(HERE, src))
            msl = run("spirv-cross", spv, "--msl", "--msl-version", "20100", "--msl-decoration-binding")
            hlsl = run("spirv-cross", spv, "--hlsl", "--shader-model", "51")
            parts.append("static const char %s_msl[] =\n%s;\n" % (name, c_string(msl)))
            parts.append("static const char %s_hlsl[] =\n%s;\n" % (name, c_string(hlsl)))
            print(name, "ok")
    open(OUT, "w").write("\n".join(parts))


main()
