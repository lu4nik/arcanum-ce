#!/usr/bin/env python3
"""Regenerate the SDL GPU versions of the ScaleFX shaders.

Takes the libretro GLSL passes (../scalefx-pass0..4.glsl), wraps the fragment
stage as Vulkan GLSL with SDL GPU resource bindings (sampled textures set 2,
uniform buffer set 3), compiles with glslang and cross-compiles with
spirv-cross to HLSL SM 5.1 (D3D12) and MSL 2.1 (Metal). Outputs are committed;
run this only after changing the shaders. Needs `glslang` and `spirv-cross`
(brew install glslang spirv-cross).
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(HERE)

UBO = """layout(std140, set = 3, binding = 0) uniform SfxUniforms {
    vec2 TextureSize;
    vec2 InputSize;
    vec2 OutputSize;
    int FrameCount;
    int FrameDirection;
};
"""

VERT = """#version 450
// Full-screen triangle; TEX0.xy runs 0..1 over the target, (0, 0) top-left.
layout(location = 0) out vec4 TEX0;
void main()
{
    vec2 uv = vec2(float((gl_VertexIndex << 1) & 2), float(gl_VertexIndex & 2));
    TEX0 = vec4(uv, 0.0, 0.0);
    gl_Position = vec4(uv.x * 2.0 - 1.0, 1.0 - uv.y * 2.0, 0.0, 1.0);
}
"""


def fragment(path):
    src = open(path).read()
    body = src.split("#elif defined(FRAGMENT)", 1)[1]
    body = body[: body.rindex("#endif")]
    out = []
    binding = 0
    ubo_done = False
    for line in body.split("\n"):
        s = line.strip()
        if re.match(r"uniform COMPAT_PRECISION (int|vec2) \w+;", s):
            if not ubo_done:
                out.append(UBO)
                ubo_done = True
            continue
        m = re.match(r"uniform sampler2D (\w+);", s)
        if m:
            out.append("layout(set = 2, binding = %d) uniform sampler2D %s;" % (binding, m.group(1)))
            binding += 1
            continue
        m = re.match(r"COMPAT_VARYING vec4 (\w+);", s)
        if m:
            if m.group(1) == "TEX0":
                out.append("layout(location = 0) in vec4 TEX0;")
            continue  # t1..t4 only feed the GL ES branch
        if s == "out COMPAT_PRECISION vec4 FragColor;":
            out.append("layout(location = 0) out vec4 FragColor;")
            continue
        out.append(line)
    text = "\n".join(out)
    # MSL is C++: its alternative operator tokens (or, and, not...) cannot be
    # variable names. Pass 2 has a variable called `or`.
    text = re.sub(r"\b(and|or|not|xor|bitand|bitor|compl)\b", r"sfx_\1", text)
    return "#version 450\n" + text + "\n", binding


def run(*cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("%s\n%s%s" % (" ".join(cmd), r.stdout, r.stderr))
    return r.stdout


def build(name, stage, glsl, tmp):
    gpath = os.path.join(tmp, name + "." + stage)
    spv = os.path.join(tmp, name + ".spv")
    open(gpath, "w").write(glsl)
    run("glslang", "-V", "--quiet", "-S", stage, "-o", spv, gpath)
    hlsl = run("spirv-cross", spv, "--hlsl", "--shader-model", "51")
    msl = run("spirv-cross", spv, "--msl", "--msl-version", "20100", "--msl-decoration-binding")
    open(os.path.join(HERE, name + ".hlsl"), "w").write(header() + hlsl)
    open(os.path.join(HERE, name + ".msl"), "w").write(header() + msl)


def header():
    # Carry the ScaleFX MIT notice into every generated file.
    src = open(os.path.join(SRC, "scalefx-pass0.glsl")).read()
    lic = src[src.index("Copyright (c)") : src.index("THE SOFTWARE.") + len("THE SOFTWARE.")]
    return ("// Generated by gen.py from the libretro ScaleFX GLSL shaders; do not edit.\n"
            "// ScaleFX by Sp00kyFox.\n//\n" + "".join("// " + l + "\n" if l else "//\n" for l in lic.split("\n")) + "\n")


def main():
    with tempfile.TemporaryDirectory() as tmp:
        build("scalefx-vert", "vert", VERT, tmp)
        for i in range(5):
            glsl, n = fragment(os.path.join(SRC, "scalefx-pass%d.glsl" % i))
            build("scalefx-pass%d" % i, "frag", glsl, tmp)
            print("pass%d: %d sampler(s)" % (i, n))


main()
